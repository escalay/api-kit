import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, relative } from 'node:path'
import { afterAll, describe, expect, it } from 'vitest'

const KIT = join(import.meta.dirname, '..')
const cli = (cwd: string, ...args: string[]) => spawnSync(process.execPath, [join(KIT, 'cli.mjs'), ...args], { cwd, encoding: 'utf8' })
// Inside the kit, so the app finds the kit's tsx and @resvg/resvg-js as an installed app finds its own
const PARENT = join(import.meta.dirname, '.generated', `brand-${process.pid}`)
afterAll(() => rm(PARENT, { recursive: true, force: true }))

const ICON = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#2563eb"/><circle cx="32" cy="32" r="14" fill="#ffffff"/></svg>\n'

/** An app with a brand folder whose brand.ts imports the kit's part, as an app imports its copy. */
const brandedApp = async (name: string, { dark = true, websiteUrl }: { dark?: boolean; websiteUrl?: string } = {}) => {
  const app = join(PARENT, name)
  await mkdir(join(app, 'brand'), { recursive: true })
  await writeFile(join(app, 'package.json'), JSON.stringify({ name, type: 'module' }))
  const part = relative(join(app, 'brand'), join(KIT, 'src/brand/index.js'))
  await writeFile(join(app, 'brand/brand.ts'), `import { defineBrand } from '${part}'\n\nexport default defineBrand({\n  name: 'cookbook',\n  title: 'Cookbook',\n  description: 'Recipes and menus for agents.',\n${websiteUrl ? `  websiteUrl: '${websiteUrl}',\n` : ''}  accent: '#2563eb',\n})\n`)
  await writeFile(join(app, 'brand/icon.svg'), ICON)
  if (dark) await writeFile(join(app, 'brand/icon-dark.svg'), ICON.replace('#2563eb', '#93c5fd'))
  return app
}

const pngSize = (base64: string) => {
  const png = Buffer.from(base64, 'base64')
  expect([...png.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10])
  return [png.readUInt32BE(16), png.readUInt32BE(20)]
}
/** The module as an app's formatter leaves it with `singleQuote`: every string in single quotes. */
const singleQuoted = (source: string) => source.replace(/^( *\w+: )(".*")(,?)$/gm, (_, key, text, comma) => `${key}'${JSON.parse(text).replaceAll("'", "\\'")}'${comma}`)
const moduleOf = async (app: string) => (await import(`${join(app, 'src/brand.gen.ts')}?t=${Date.now()}`)).BRAND_ASSETS

describe('kit brand', () => {
  it('renders every size from the app’s brand into src/brand.gen.ts, the inline icon under 10 KB', async () => {
    const app = await brandedApp('render')
    const rendered = cli(app, 'brand')
    expect(rendered.status, rendered.stderr).toBe(0)
    expect(rendered.stdout).toContain('src/brand.gen.ts')
    const source = await readFile(join(app, 'src/brand.gen.ts'), 'utf8')
    expect(source).toMatch(/^\/\/ Generated by `kit brand`/)
    const assets = await moduleOf(app)
    expect(assets.inputsHash).toMatch(/^[0-9a-f]{64}$/)
    expect([assets.svg, assets.svgDark]).toEqual([ICON, ICON.replace('#2563eb', '#93c5fd')])
    for (const size of [16, 32, 48, 96, 180, 192, 512]) expect(pngSize(assets.png[size]), String(size)).toEqual([size, size])
    // Dark icons are never inline: only the sizes served at this host
    expect(Object.keys(assets.pngDark)).toEqual(['192', '512'])
    for (const size of [192, 512]) expect(pngSize(assets.pngDark[size]), `dark ${size}`).toEqual([size, size])
    expect(pngSize(assets.og)).toEqual([1200, 630])
    expect(Buffer.from(assets.png[96], 'base64').length).toBeLessThan(10_240)
  })

  it('brings an inline icon over 10 KB under it in at most 256 colours, and leaves the other sizes alone', async () => {
    const app = await brandedApp('palette', { dark: false })
    // Rotated cells in six colours: antialiasing makes thousands of shades, more than 10 KB as a true-colour PNG
    let seed = 7
    const next = () => (seed = (seed * 1_103_515_245 + 12_345) % 2_147_483_648) / 2_147_483_648
    const colours = ['#2563eb', '#93c5fd', '#1e3a8a', '#ffffff', '#f59e0b', '#10b981']
    const cells = Array.from({ length: 32 * 32 }, (_, at) => {
      const [x, y] = [(at % 32) * 2, Math.floor(at / 32) * 2]
      return `<rect x="${x}" y="${y}" width="2" height="2" fill="${colours[Math.floor(next() * 6)]}" transform="rotate(${Math.floor(next() * 30)} ${x + 1} ${y + 1})"/>`
    })
    await writeFile(join(app, 'brand/icon.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${cells.join('')}</svg>\n`)
    expect(cli(app, 'brand').status).toBe(0)
    const assets = await moduleOf(app)
    const inline = Buffer.from(assets.png[96], 'base64')
    expect(inline.length).toBeLessThan(10_240)
    // Colour type 3: indexed; the 192 stays true colour with alpha (6)
    expect([inline[25], Buffer.from(assets.png[192], 'base64')[25]]).toEqual([3, 6])
    expect(pngSize(assets.png[96])).toEqual([96, 96])
  })

  it('--check: current after rendering, stale once an input changes, and the rendered bytes never count', async () => {
    const app = await brandedApp('check', { dark: false })
    expect(cli(app, 'brand').status).toBe(0)
    const current = cli(app, 'brand', '--check')
    expect([current.status, current.stdout]).toEqual([0, 'src/brand.gen.ts matches brand/\n'])
    // Another machine renders other bytes from the same inputs: still current
    const path = join(app, 'src/brand.gen.ts')
    const source = await readFile(path, 'utf8')
    await writeFile(path, source.replace(/(16: ")[A-Za-z0-9+/]{8}/, '$1AAAAAAAA'))
    expect(cli(app, 'brand', '--check').status).toBe(0)
    await writeFile(join(app, 'brand/icon.svg'), ICON.replace('#ffffff', '#000000'))
    const stale = cli(app, 'brand', '--check')
    expect([stale.status, stale.stdout]).toEqual([1, 'stale    brand/ changed since src/brand.gen.ts was written: `kit brand` renders it again\n'])
  })

  it('reads a module the app’s formatter rewrote in single quotes: current until an input changes, and a heavy icon still found', async () => {
    const app = await brandedApp('single-quotes', { dark: false })
    expect(cli(app, 'add', 'core', 'brand').status).toBe(0)
    expect(cli(app, 'brand').status).toBe(0)
    const path = join(app, 'src/brand.gen.ts')
    const source = singleQuoted(await readFile(path, 'utf8'))
    expect(source).toMatch(/^ {2}inputsHash: '[0-9a-f]{64}',$/m)
    expect(source).not.toMatch(/: "/)
    await writeFile(path, source)
    const current = cli(app, 'brand', '--check')
    expect([current.status, current.stdout]).toEqual([0, 'src/brand.gen.ts matches brand/\n'])
    await writeFile(path, source.replace(/(96: ')([A-Za-z0-9+/=]+)'/, (_, start) => `${start}${'A'.repeat(14_000)}'`))
    const heavy = cli(app, 'doctor')
    expect(heavy.status).toBe(1)
    expect(heavy.stdout).toContain('brand    the inline icon is 10.3 KB, over the 10 KB Claude shows')
    await writeFile(path, source)
    await writeFile(join(app, 'brand/icon.svg'), ICON.replace('#ffffff', '#000000'))
    expect(cli(app, 'brand', '--check').status).toBe(1)
  })

  it('add brand keeps lint, format and the secrets scan off src/brand.gen.ts in an app made before the part, once', async () => {
    const app = await mkdtemp(join(tmpdir(), 'kit-brand-'))
    await writeFile(join(app, 'package.json'), JSON.stringify({ name: 'cookbook', type: 'module' }))
    // As a new app had them before the brand part
    for (const name of ['.oxfmtrc.json', '.oxlintrc.json']) await writeFile(join(app, name), `${JSON.stringify({ semi: false, ignorePatterns: ['src/kit/**', 'src/guide.gen.ts'] }, null, 2)}\n`)
    await writeFile(join(app, '.gitleaks.toml'), "[extend]\nuseDefault = true\n\n[allowlist]\npaths = ['''src/kit/kit\\.json''']\n")
    const added = cli(app, 'add', 'brand')
    expect(added.status, added.stderr).toBe(0)
    expect(added.stdout).toContain('Ignored src/brand.gen.ts in .oxfmtrc.json, .oxlintrc.json and .gitleaks.toml')
    for (const name of ['.oxfmtrc.json', '.oxlintrc.json']) expect(JSON.parse(await readFile(join(app, name), 'utf8')), name).toEqual({ semi: false, ignorePatterns: ['src/kit/**', 'src/guide.gen.ts', 'src/brand.gen.ts'] })
    expect(await readFile(join(app, '.gitleaks.toml'), 'utf8')).toBe("[extend]\nuseDefault = true\n\n[allowlist]\npaths = ['''src/kit/kit\\.json''', '''src/brand\\.gen\\.ts''']\n")
    const files = async () => Promise.all(['.oxfmtrc.json', '.oxlintrc.json', '.gitleaks.toml'].map((name) => readFile(join(app, name), 'utf8')))
    const before = await files()
    const again = cli(app, 'add', 'brand')
    expect(again.stdout).not.toContain('src/brand.gen.ts in')
    expect(await files()).toEqual(before)
  })

  it('add brand prints the lines to add where it can’t read the config', async () => {
    const app = await mkdtemp(join(tmpdir(), 'kit-brand-'))
    await writeFile(join(app, 'package.json'), JSON.stringify({ name: 'cookbook', type: 'module' }))
    await writeFile(join(app, '.oxfmtrc.json'), '{ // mine\n}\n')
    await writeFile(join(app, '.gitleaks.toml'), "[allowlist]\npaths = [\n  '''src/kit/kit\\.json''',\n]\n")
    const added = cli(app, 'add', 'brand')
    expect(added.status, added.stderr).toBe(0)
    expect(added.stdout).toContain('Add "src/brand.gen.ts" to ignorePatterns in .oxfmtrc.json')
    expect(added.stdout).toContain("Add '''src/brand\\.gen\\.ts''' to [allowlist] paths in .gitleaks.toml")
    expect(await readFile(join(app, '.oxfmtrc.json'), 'utf8')).toBe('{ // mine\n}\n')
  })

  it('says how to install the renderer when the app has none', async () => {
    const app = await mkdtemp(join(tmpdir(), 'kit-brand-'))
    await mkdir(join(app, 'brand'))
    await writeFile(join(app, 'brand/brand.ts'), "export default { name: 'cookbook', title: 'Cookbook', description: 'Recipes.', accent: '#2563eb' }\n")
    await writeFile(join(app, 'brand/icon.svg'), ICON)
    const missing = cli(app, 'brand')
    expect(missing.status).toBe(1)
    expect(missing.stderr).toContain('`pnpm add -D @resvg/resvg-js`')
    expect(existsSync(join(app, 'src/brand.gen.ts'))).toBe(false)
  })

  it('add brand scaffolds a monogram brand named after the app, and keeps one already there', async () => {
    const app = await mkdtemp(join(tmpdir(), 'kit-brand-'))
    await writeFile(join(app, 'package.json'), JSON.stringify({ name: 'cookbook', type: 'module' }))
    const added = cli(app, 'add', 'brand')
    expect(added.status, added.stderr).toBe(0)
    expect(added.stdout).toContain('brand/brand.ts')
    const brand = await readFile(join(app, 'brand/brand.ts'), 'utf8')
    expect(brand).toContain("import { defineBrand } from '../src/kit/brand/index.js'")
    expect(brand).toContain("  name: 'cookbook',\n  title: 'Cookbook',")
    expect(await readFile(join(app, 'brand/icon.svg'), 'utf8')).toMatch(/fill="#[0-9a-f]{6}"[\s\S]*>C</)
    await writeFile(join(app, 'brand/brand.ts'), '// mine\n')
    expect(cli(app, 'add', 'brand').status).toBe(0)
    expect(await readFile(join(app, 'brand/brand.ts'), 'utf8')).toBe('// mine\n')
  })

  it('doctor: a note for a brand never rendered and for a subdomain host, a finding for a stale one or a heavy icon', async () => {
    const app = await brandedApp('doctor', { dark: false, websiteUrl: 'https://gw.example.com' })
    expect(cli(app, 'add', 'core', 'brand').status).toBe(0)
    const unrendered = cli(app, 'doctor')
    expect(unrendered.status, unrendered.stdout).toBe(1)
    expect(unrendered.stdout).toContain('brand    src/brand.gen.ts is missing: `kit brand` writes it')
    expect(cli(app, 'brand').status).toBe(0)
    const rendered = cli(app, 'doctor')
    expect(rendered.status, rendered.stdout).toBe(0)
    expect(rendered.stdout).toContain("note     claude.ai shows the favicon of example.com in its connector list, not this server's icon: serve the same icon there (gw.example.com is a subdomain)")
    // An SVG-only module, as `kit init` writes before the first render: a note, never a failure
    const path = join(app, 'src/brand.gen.ts')
    const source = await readFile(path, 'utf8')
    await writeFile(path, source.replace(/\n {2}png: \{[^}]*\},/, ''))
    const svgOnly = cli(app, 'doctor')
    expect(svgOnly.status, svgOnly.stdout).toBe(0)
    expect(svgOnly.stdout).toContain('note     brand: src/brand.gen.ts has the SVG only: `kit brand` renders the favicon, PNG icons and OG card (it needs `pnpm add -D @resvg/resvg-js`)')
    await writeFile(path, source.replace(/(96: ")([A-Za-z0-9+/=]+)"/, (_, start) => `${start}${'A'.repeat(14_000)}"`))
    const heavy = cli(app, 'doctor')
    expect(heavy.status).toBe(1)
    expect(heavy.stdout).toContain('brand    the inline icon is 10.3 KB, over the 10 KB Claude shows: simplify brand/icon.svg (flat colours, no filters, gradients or embedded images), then `kit brand`')
    await writeFile(path, source)
    await writeFile(join(app, 'brand/icon.svg'), ICON.replace('#ffffff', '#000000'))
    const stale = cli(app, 'doctor')
    expect(stale.status).toBe(1)
    expect(stale.stdout).toContain('stale    brand/ changed since src/brand.gen.ts was written: `kit brand` renders it again')
  })

  it('doctor reads a two-label public suffix as part of the root domain', async () => {
    for (const [host, note] of [['example.co.uk', null], ['www.example.co.uk', null], ['gw.example.co.uk', 'example.co.uk'], ['gw.example.com.au', 'example.com.au'], ['example.com', null]] as const) {
      const app = await brandedApp(`suffix-${host}`, { dark: false, websiteUrl: `https://${host}` })
      expect(cli(app, 'add', 'core', 'brand').status).toBe(0)
      const lines = cli(app, 'doctor').stdout.split('\n').filter((line) => line.includes('claude.ai shows'))
      expect(lines, host).toEqual(note ? [`note     claude.ai shows the favicon of ${note} in its connector list, not this server's icon: serve the same icon there (${host} is a subdomain)`] : [])
    }
  })

  it('doctor leaves brand files alone in an app without the brand part, until it has a brand module', async () => {
    const app = await brandedApp('not-installed', { dark: false })
    expect(cli(app, 'add', 'core').status).toBe(0)
    const plain = cli(app, 'doctor')
    expect(plain.status, plain.stdout).toBe(0)
    expect(plain.stdout).not.toMatch(/brand/)
    // A module the app wrote is checked like any other
    expect(cli(app, 'brand').status).toBe(0)
    await writeFile(join(app, 'brand/icon.svg'), ICON.replace('#ffffff', '#000000'))
    const stale = cli(app, 'doctor')
    expect(stale.status).toBe(1)
    expect(stale.stdout).toContain('stale    brand/ changed since src/brand.gen.ts was written: `kit brand` renders it again')
  })

  it('add and doctor find the app at the nearest package.json above --dir, at any depth', async () => {
    for (const dir of ['kit', 'src/kit']) {
      // A folder above the app with configs of its own, which add must never touch
      const outer = await mkdtemp(join(tmpdir(), 'kit-brand-'))
      const outerConfig = `${JSON.stringify({ ignorePatterns: [] }, null, 2)}\n`
      await writeFile(join(outer, '.oxfmtrc.json'), outerConfig)
      const app = join(outer, 'cookbook')
      await mkdir(app)
      await writeFile(join(app, 'package.json'), JSON.stringify({ name: 'cookbook', type: 'module' }))
      await writeFile(join(app, '.oxfmtrc.json'), `${JSON.stringify({ ignorePatterns: [] }, null, 2)}\n`)
      const added = cli(app, 'add', 'core', 'brand', '--dir', dir)
      expect(added.status, added.stderr).toBe(0)
      expect(existsSync(join(outer, 'brand')), dir).toBe(false)
      expect(await readFile(join(outer, '.oxfmtrc.json'), 'utf8'), dir).toBe(outerConfig)
      expect(await readFile(join(app, 'brand/brand.ts'), 'utf8'), dir).toContain(`from '../${dir}/brand/index.js'`)
      expect(JSON.parse(await readFile(join(app, '.oxfmtrc.json'), 'utf8')).ignorePatterns, dir).toEqual(['src/brand.gen.ts'])
      const doctor = cli(app, 'doctor', '--dir', dir)
      expect(doctor.stdout, dir).toContain('brand    src/brand.gen.ts is missing: `kit brand` writes it')
    }
  })

  it('add brand with no package.json above --dir scaffolds nothing and says how to name the app', async () => {
    const outer = await mkdtemp(join(tmpdir(), 'kit-brand-'))
    const app = join(outer, 'cookbook')
    await mkdir(app)
    const added = cli(app, 'add', 'brand', '--dir', 'kit')
    expect(added.status, added.stderr).toBe(0)
    expect(added.stdout).toContain('Brand: no package.json above kit, so brand/ was not made: `kit add brand --dir kit --app <app>` names the app')
    expect(existsSync(join(app, 'brand'))).toBe(false)
    expect(existsSync(join(outer, 'brand'))).toBe(false)
    // --app names it
    const named = cli(app, 'add', 'brand', '--dir', 'kit', '--app', '.')
    expect(named.status, named.stderr).toBe(0)
    expect(existsSync(join(app, 'brand/brand.ts'))).toBe(true)
  })

  it('doctor notes an installed brand part with no brand files, without failing', async () => {
    const app = await mkdtemp(join(tmpdir(), 'kit-brand-'))
    await writeFile(join(app, 'package.json'), JSON.stringify({ name: 'cookbook', type: 'module' }))
    expect(cli(app, 'add', 'core', 'brand').status).toBe(0)
    await rm(join(app, 'brand'), { recursive: true })
    const noted = cli(app, 'doctor')
    expect(noted.status, noted.stdout).toBe(0)
    expect(noted.stdout).toContain('note     brand: no brand/brand.ts and brand/icon.svg: `kit add brand` scaffolds them (a brand is optional)')
  })
})
